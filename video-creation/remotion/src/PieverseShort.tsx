// Built by comp-builder in SHORT mode per video-creation/longform-edited/skills/longform-to-short/longform-to-short.md section 5
// Stage B (16:9-SOURCED MODE: no full vertical; the spans were painted from the 16:9 comp, face spans on the measured crop).
// Sources (all on SHORT seconds / frames):
//   _previews/short/work/spans.json            the span table: one muted OffthreadVideo per span-NN.mp4, laid end to end
//                                               (small linear intermediates; the master is NEVER seeked)
//   assets/short/variants.json                 the variety overlays: NONE for this video (no Envato, no ChatGPT stills)
//   assets/short/vertical-cards.json           the native-vertical rebuilds: C1 (diagram, agent lit) + D5 (container, s4 to s8)
//   remotion/src/PieverseShortCaptions.ts      ZCAPTIONS + CAPTION_WINDOWS, generated by s_captions, rendered exactly as given
// The comp has NO audio (mix_short.py lays the VO spans + the shared CTA take; this video is no-music, no-SFX by Mike's ruling).
// Every asset resolves against the render's public dir = media/pieverse/_previews/short/work (vertical cards copied into
// work/vertical-cards/). No watermark. Transition ids are tagged in comments so a reviewer can grep them against TRANSITIONS.md.
import React from 'react';
import { AbsoluteFill, Freeze, Img, interpolate, OffthreadVideo, Sequence, staticFile, useCurrentFrame } from 'remotion';
import { TransitionSeries, linearTiming } from '@remotion/transitions';
import { flip } from '@remotion/transitions/flip';
import { loadFont as loadMontserrat } from '@remotion/google-fonts/Montserrat';
import { loadFont as loadPlayfair } from '@remotion/google-fonts/PlayfairDisplay';
import { ZCAPTIONS, CAPTION_WINDOWS } from './PieverseShortCaptions';

const { fontFamily: MONTSERRAT } = loadMontserrat('normal', { weights: ['900'], subsets: ['latin'] });
const { fontFamily: PLAYFAIR } = loadPlayfair('normal', { weights: ['900'], subsets: ['latin'] });

export const FPS = 30;
export const WIDTH = 1080;
export const HEIGHT = 1920;
const clamp = { extrapolateLeft: 'clamp', extrapolateRight: 'clamp' } as const;
const FILL: React.CSSProperties = { position: 'absolute', left: 0, top: 0, width: WIDTH, height: HEIGHT, objectFit: 'cover' };

// ---------------------------------------------------------------------------------------------------------------------
// 1. The span table (spans.json verbatim). out = out_start in SHORT seconds; frames = the intermediate's exact frame count
//    (ffprobe-verified 2026-11-14: 290 / 53 / 246 / 230). The spans must butt end to end, frame exact.
// ---------------------------------------------------------------------------------------------------------------------
type Span = { i: number; file: string; out: number; frames: number; sourced: 'FACE' | 'COVER'; role: string; srcStart: number };
export const SPANS: Span[] = [
  { i: 1, file: 'span-01.mp4', out: 0.0, frames: 290, sourced: 'FACE', role: 'hook', srcStart: 0.0 },
  { i: 2, file: 'span-02.mp4', out: 9.6667, frames: 53, sourced: 'COVER', role: 'body', srcStart: 62.44 },
  { i: 3, file: 'span-03.mp4', out: 11.4333, frames: 246, sourced: 'FACE', role: 'body', srcStart: 146.14 },
  { i: 4, file: 'span-04.mp4', out: 19.6333, frames: 230, sourced: 'FACE', role: 'kicker', srcStart: 358.66 },
];
const SPAN_RUNS = SPANS.map((s) => ({ ...s, fromF: Math.round(s.out * FPS), toF: Math.round(s.out * FPS) + s.frames }));
SPAN_RUNS.forEach((s, k) => {
  const want = k === 0 ? 0 : SPAN_RUNS[k - 1].toF;
  if (s.fromF !== want) throw new Error(`span ${s.i}: starts at frame ${s.fromF}, the previous span ends at ${want} (spans must butt end to end)`);
});
export const SPANS_F = SPAN_RUNS[SPAN_RUNS.length - 1].toF;            // 819 = 27.3 s (spans_total_seconds)
export const OUTRO_S = 3.0;                                            // s_comp: target 30 s - 27.3 s of spans, never under 3.0
export const DUR = Math.round(30.3 * FPS);                             // 909 (spans 27.3 s + the 3.0 s outro)
if (DUR - SPANS_F !== Math.round(OUTRO_S * FPS)) throw new Error(`outro is ${DUR - SPANS_F} frames, want ${OUTRO_S * FPS}`);
const SEAMS_F = SPAN_RUNS.slice(1).map((s) => s.fromF);                // 290, 343, 589
const spanAt = (f: number) => SPAN_RUNS.find((s) => f >= s.fromF && f < s.toF);

// The variety overlays (assets/short/variants.json): the video has no Envato clip and no ChatGPT still under any span, so the
// table is declared EMPTY on purpose (lint_covers accepts a declared-empty table).
type Cover = { tIn: number; tOut: number; kind: 'still' | 'vid'; ref: string };
export const COVERS: Cover[] = [];

// ---------------------------------------------------------------------------------------------------------------------
// 2. The native-vertical cards (assets/short/vertical-cards.json `cards`, overlay_short windows verbatim). Hard in / out on
//    the window edges (frame = round(t * 30)); each window is clamped to the span it opens in, because the json's edges sit on
//    the plan clock and can land up to half a frame past the span (D5 ends 19.65 = frame 589.5, span 3 ends at frame 589).
//    D5 steps through the 16:9 spotlight progression (D5-not-published-v.states.json, SHORT seconds) as HARD swaps (the deck
//    cards are pixel-locked states, as in the 16:9 comp). Both get the 16:9's slow hold push (comp-build 7a, never dead still):
//    C1 1.00 -> 1.03 about the LIT agent node, D5 1.00 -> 1.02 about the centre. No holds in the json (`holds: []`).
// ---------------------------------------------------------------------------------------------------------------------
type CardState = { from: number; png: string };
type NativeCard = { id: string; kind: 'diagram' | 'container'; win: [number, number]; states: CardState[]; push: { s: number; ox: number; oy: number } };
const NATIVE_CARDS: NativeCard[] = [
  { id: 'C1', kind: 'diagram', win: [9.68, 11.44], states: [{ from: 9.68, png: 'C1-agent-v' }], push: { s: 1.03, ox: 540, oy: 684 } },
  { id: 'D5', kind: 'container', win: [13.455, 19.65], push: { s: 1.02, ox: 540, oy: 960 }, states: [
    { from: 13.455, png: 'D5-not-published-v-s4' },
    { from: 15.04, png: 'D5-not-published-v-s5' },     // Agents running lights
    { from: 15.92, png: 'D5-not-published-v-s6' },     // Paying subscribers
    { from: 17.0, png: 'D5-not-published-v-s7' },      // Revenue
    { from: 18.12, png: 'D5-not-published-v-s8' },     // footer: At least not anywhere I checked.
  ] },
];
const CARD_RUNS = NATIVE_CARDS.map((c) => {
  const aF = Math.round(c.win[0] * FPS);
  const span = spanAt(aF);
  if (!span) throw new Error(`card ${c.id}: window start ${c.win[0]} is outside every span`);
  const bF = Math.min(Math.round(c.win[1] * FPS), span.toF);
  if (bF - aF < 1) throw new Error(`card ${c.id}: empty window`);
  return { ...c, aF, bF, cues: c.states.map((s) => ({ f: Math.round(s.from * FPS), png: s.png })) };
});

// ---------------------------------------------------------------------------------------------------------------------
// 3. Face HOLD (comp-side, measured 2026-11-14): the LAST frame of span-04.mp4 (frame 229) is pure black in the painted
//    intermediate (mean luma 16; spans 2 and 3 carry the same black last frame, both under a native card). It is span 4's
//    real picture that must show, so frame 228 (his face under the F8-out warm wash) is HELD over short frame 818, and the
//    outro holds the same frame: "the last span's final frame" = the last real picture frame.
//    A real <Freeze> wrapped in a zero-offset Sequence (comp-build 6a rule 1: Remotion 4.0.462 adds the PARENT Sequence's
//    `from` to the frozen frame), muted, the same source and the same (identity) transform as the live span layer.
// ---------------------------------------------------------------------------------------------------------------------
const HOLD = { file: 'span-04.mp4', frame: 228 };
const HOLD_FROM_F = SPANS_F - 1;                                       // 818: span 4's black last frame
const HoldFrame: React.FC = () => (
  <AbsoluteFill style={{ backgroundColor: '#000' }}>
    <Sequence from={0} layout="none">
      <Freeze frame={HOLD.frame}>
        <OffthreadVideo src={staticFile(HOLD.file)} muted style={FILL} />
      </Freeze>
    </Sequence>
  </AbsoluteFill>
);

// ---------------------------------------------------------------------------------------------------------------------
// 4. Transitions (the video's own family, TRANSITIONS.md): the face pick hand:film-burn. Every seam in this short is a
//    face cut (F1 -> C1, C1 -> F4, D5 -> F8), so each seam takes a FAST film-burn hit: 9 frames (0.3 s) centred on the seam
//    frame, warm radial flash, screen blend, the 16:9's gradient. The 16:9's F4-out burn (row 2:25.2, centred on the D5
//    cut = short frame 404, measured on span-03 chroma: rise from local frame 50, peak 61, decay to 72) loses its card-side
//    half under the clean native D5 card, so that half is redrawn ON the card (frames 404-415) with the 16:9's numbers.
//    The outro card turns in with the video's title-card pick rmn:flip (from-right, 0.40 s), never flipping back out.
// ---------------------------------------------------------------------------------------------------------------------
const BURN_PEAK = 0.45;            // the 16:9 comp's film-burn intensity (TRANSITIONS.md section 3: kept low)
const BURN_HALF = 11;              // the 16:9 burn: 23 frames centred on the cut
const SEAM_HALF = 4;               // the short's seam hit: 9 frames = 0.3 s
const SEAM_PEAK = 0.55;            // a touch hotter than the 16:9 so the cut between two moments reads as one hit
const TURN_F = Math.round(0.4 * FPS);   // rmn:flip, 12 frames (the 16:9 card turn)

const FilmBurn: React.FC<{ durF: number; seed: number; peak: number; offset?: number }> = ({ durF, seed, peak, offset = 0 }) => {
  const f = useCurrentFrame() + offset;
  const p = Math.min(1, Math.max(0, f / (durF - 1)));
  const a = Math.sin(Math.PI * p);
  const dir = seed % 2 === 0 ? 1 : -1;
  const cx = 50 + dir * (p - 0.5) * 60;
  return (
    <AbsoluteFill style={{ pointerEvents: 'none', mixBlendMode: 'screen', opacity: peak * a }}>
      <AbsoluteFill style={{ background: `radial-gradient(ellipse 95% 75% at ${cx}% 42%, rgba(255,222,160,1) 0%, rgba(255,150,60,.92) 26%, rgba(214,70,22,.6) 52%, rgba(0,0,0,0) 80%)` }} />
      <AbsoluteFill style={{ background: `radial-gradient(ellipse 55% 45% at ${100 - cx}% 78%, rgba(255,186,96,.55) 0%, rgba(0,0,0,0) 72%)` }} />
    </AbsoluteFill>
  );
};
const D5_BURN_CENTRE_F = CARD_RUNS.find((c) => c.id === 'D5')!.aF;     // 404, the 16:9 F4-out cut

// ---------------------------------------------------------------------------------------------------------------------
// 5. Layers
// ---------------------------------------------------------------------------------------------------------------------
const NativeCardEl: React.FC<{ run: (typeof CARD_RUNS)[number] }> = ({ run }) => {
  const lf = useCurrentFrame();
  const absF = run.aF + lf;
  let cur = run.cues[0];
  for (const c of run.cues) if (c.f <= absF) cur = c;
  const s = interpolate(lf, [0, run.bF - run.aF], [1, run.push.s], clamp);
  return (
    <AbsoluteFill style={{ backgroundColor: '#0a0c10', overflow: 'hidden' }}>
      <AbsoluteFill style={{ transformOrigin: `${run.push.ox}px ${run.push.oy}px`, transform: `scale(${s})` }}>
        <Img src={staticFile(`vertical-cards/${cur.png}.png`)} style={FILL} />
      </AbsoluteFill>
    </AbsoluteFill>
  );
};

// Captions: the house Montserrat style (comp-build section 8), SAFE ZONE for a short (bottom pad 320 px -> block at y ~1420-1600,
// maxWidth 860 so the 1.12 pop + the 12 px stroke stay inside 1080). Shown ONLY inside CAPTION_WINDOWS, exactly as generated;
// a group hides at min(next.t, max(t + 1.3, e), the end of the window holding its t) (longform-to-short.md, lets-get-rich rule).
// The card text of C1 / D5 ends above y 1380 (VERTICAL-CARDS-QA.json), so a caption never sits on card text.
const CAP_BOTTOM = 320;
const CAP_MAX_W = 860;
const captionAt = (t: number) => {
  if (!CAPTION_WINDOWS.some(([a, b]) => t >= a && t < b)) return null;
  let k = -1;
  for (let j = 0; j < ZCAPTIONS.length; j++) { if (ZCAPTIONS[j].t <= t) k = j; else break; }
  if (k < 0) return null;
  const cur = ZCAPTIONS[k];
  const next = ZCAPTIONS[k + 1];
  const win = CAPTION_WINDOWS.find(([a, b]) => cur.t >= a && cur.t < b);
  const end = Math.min(next ? next.t : Infinity, Math.max(cur.t + 1.3, cur.e), win ? win[1] : cur.e);
  return t < end ? cur : null;
};
const Captions: React.FC = () => {
  const frame = useCurrentFrame();
  const cur = captionAt(frame / FPS);
  if (!cur) return null;
  const lf = frame - Math.round(cur.t * FPS);
  const pop = interpolate(lf, [0, 3, 6], [0.7, 1.12, 1], clamp);
  return (
    <AbsoluteFill style={{ pointerEvents: 'none' }}>
      <div style={{ position: 'absolute', left: 0, right: 0, bottom: CAP_BOTTOM, display: 'flex', justifyContent: 'center' }}>
        <div style={{
          maxWidth: CAP_MAX_W, textAlign: 'center', fontFamily: `${MONTSERRAT}, 'Arial Black', 'Segoe UI', sans-serif`, fontWeight: 900,
          fontSize: 84, lineHeight: 1.08, color: '#fff', textTransform: 'lowercase', WebkitTextStroke: '12px #000', paintOrder: 'stroke fill',
          transform: `scale(${pop})`, transformOrigin: '50% 100%',
        }}>
          {cur.h}
        </div>
      </div>
    </AbsoluteFill>
  );
};

// The outro: a full-frame TITLE SLIDE in the locked container stylesheet (assets/slide-sources/containers.html `.frame.title`:
// --bg-deep #0a0c10, the cyan orb top right + the green orb bottom left, Playfair Display 900 headline, gradient divider), reflowed
// for 1080x1920, reading exactly WATCH THE FULL VIDEO with the accent word in green (--accent-green #00e68a), and a downward
// arrow glyph (green -> cyan, a slow bob) pointing at the link below. No em dash, no other words.
const OutroCard: React.FC = () => {
  const f = useCurrentFrame();
  const arrowIn = interpolate(f, [TURN_F, TURN_F + 8], [0, 1], clamp);
  const bob = Math.sin(((f - TURN_F) / FPS) * Math.PI * 2 * 0.8) * 12 * arrowIn;
  return (
    <AbsoluteFill style={{ backgroundColor: '#0a0c10', overflow: 'hidden' }}>
      <div style={{ position: 'absolute', width: 820, height: 820, right: -300, top: -300, borderRadius: '50%', background: '#00c2ff', filter: 'blur(120px)', opacity: 0.3 }} />
      <div style={{ position: 'absolute', width: 680, height: 680, left: -300, bottom: -280, borderRadius: '50%', background: '#00e68a', filter: 'blur(120px)', opacity: 0.16 }} />
      <div style={{ position: 'absolute', left: 96, right: 96, top: 520, display: 'flex', flexDirection: 'column', alignItems: 'flex-start' }}>
        <div style={{ fontFamily: `${PLAYFAIR}, serif`, fontWeight: 900, fontSize: 168, lineHeight: 1.02, letterSpacing: '-0.025em', color: '#e8eaf0' }}>
          WATCH<br />THE <span style={{ color: '#00e68a' }}>FULL</span><br />VIDEO
        </div>
        <div style={{ width: 96, height: 5, borderRadius: 3, marginTop: 52, background: 'linear-gradient(90deg, #00e68a, #00c2ff)' }} />
        <svg width={132} height={200} viewBox="0 0 132 200" style={{ marginTop: 92, opacity: arrowIn, transform: `translateY(${bob}px)` }}>
          <defs>
            <linearGradient id="pvShortArrow" x1="0" y1="0" x2="0" y2="1">
              <stop offset="0" stopColor="#00e68a" />
              <stop offset="1" stopColor="#00c2ff" />
            </linearGradient>
          </defs>
          <path d="M66 10 V176 M14 124 L66 178 L118 124" stroke="url(#pvShortArrow)" strokeWidth={16} strokeLinecap="round" strokeLinejoin="round" fill="none" />
        </svg>
      </div>
    </AbsoluteFill>
  );
};

// the outro scene: span 4's held frame turns away and the card flips in (rmn:flip from-right, the video's card pick)
const OUTRO_F = DUR - SPANS_F;                                         // 90 frames
const OutroScene: React.FC = () => (
  <AbsoluteFill style={{ backgroundColor: '#0a0c10' }}>
    <TransitionSeries>
      <TransitionSeries.Sequence durationInFrames={TURN_F}>
        <HoldFrame />
      </TransitionSeries.Sequence>
      <TransitionSeries.Transition presentation={flip({ direction: 'from-right' })} timing={linearTiming({ durationInFrames: TURN_F })} />
      <TransitionSeries.Sequence durationInFrames={OUTRO_F}>
        <OutroCard />
      </TransitionSeries.Sequence>
    </TransitionSeries>
  </AbsoluteFill>
);

// ---------------------------------------------------------------------------------------------------------------------
// 6. The composition: spans -> native cards -> burns -> face hold -> outro -> captions (topmost). No audio.
// ---------------------------------------------------------------------------------------------------------------------
export const PieverseShort: React.FC = () => (
  <AbsoluteFill style={{ backgroundColor: '#000' }}>
    {SPAN_RUNS.map((s) => (
      <Sequence key={s.file} from={s.fromF} durationInFrames={s.frames} name={`span ${s.i} ${s.role} (${s.sourced}, src ${s.srcStart})`}>
        <OffthreadVideo src={staticFile(s.file)} muted style={FILL} />
      </Sequence>
    ))}
    {CARD_RUNS.map((c) => (
      <Sequence key={c.id} from={c.aF} durationInFrames={c.bF - c.aF} name={`native card ${c.id} (${c.kind})`}>
        <NativeCardEl run={c} />
      </Sequence>
    ))}
    {/* hand:film-burn (TRANSITIONS.md 2:25.2, F4 out to D5 RETURN): the card-side half, redrawn over the native D5 */}
    <Sequence from={D5_BURN_CENTRE_F} durationInFrames={BURN_HALF + 1} name="hand:film-burn 2:25.2 card-side half">
      <FilmBurn durF={2 * BURN_HALF + 1} seed={6} peak={BURN_PEAK} offset={BURN_HALF} />
    </Sequence>
    {/* hand:film-burn seam hits (the face pick, fast): F1 -> C1, C1 -> F4, D5 -> F8 */}
    {SEAMS_F.map((f, i) => (
      <Sequence key={`seam${f}`} from={f - SEAM_HALF} durationInFrames={2 * SEAM_HALF + 1} name={`hand:film-burn seam ${i + 1} @${f}`}>
        <FilmBurn durF={2 * SEAM_HALF + 1} seed={i} peak={SEAM_PEAK} />
      </Sequence>
    ))}
    <Sequence from={HOLD_FROM_F} durationInFrames={SPANS_F - HOLD_FROM_F} name="face hold: span 4 frame 228 over its black last frame">
      <HoldFrame />
    </Sequence>
    <Sequence from={SPANS_F} durationInFrames={OUTRO_F} name="outro: rmn:flip to WATCH THE FULL VIDEO">
      <OutroScene />
    </Sequence>
    <Captions />
  </AbsoluteFill>
);
