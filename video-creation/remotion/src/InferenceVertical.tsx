// ---------------------------------------------------------------------------------------------------- §8 CAPTIONS, portrait
// The SAME generated file + windows + OFF holds as the 16:9 (asserted); restyled for 9:16: the house Montserrat style verbatim,
// 82 px (the longest group 'everything anyone' fits the 1080 width with the 1.12 pop), on his chest below the chin, topmost.
const CAPTION_SRC: [number, number][] = [[0.0, 6.467], [61.3, 66.933], [141.933, 147.7], [158.033, 164.633], [176.367, 190.4]];
if (JSON.stringify(CAPTION_SRC) !== JSON.stringify(CAPTION_WINDOWS) || JSON.stringify(CAPTION_SRC) !== JSON.stringify(P169.CAPTION_SRC)) throw new Error('CAPTION_SRC drifted');
const CAPTION_OFF = P169.CAPTION_OFF;
const Captions: React.FC = () => {
  const t = useT();
  if (!CAPTION_WINDOWS.some(([a, b]) => t >= a && t < b)) return null;
  if (CAPTION_OFF.some(([a, b]) => t >= a && t < b)) return null;
  let cur: { t: number; h: string } | null = null;
  for (const c of ZCAPTIONS) {
    if (c.t <= t + 1e-6) cur = c;
    else break;
  }
  if (!cur) return null;
  const nextT = (ZCAPTIONS.find((c) => c.t > cur!.t) || { t: Infinity }).t;
  if (t >= Math.min(nextT, cur.t + 1.3)) return null;
  const d = t - cur.t;
  const s = interpolate(d, [0, 0.08, 0.16], [0.7, 1.12, 1], CL);
  return (
    <AbsoluteFill style={{ justifyContent: 'flex-end', alignItems: 'center', paddingBottom: 200 }}>
      <div
        style={{
          fontFamily: "Montserrat,'Arial Black','Segoe UI',sans-serif",
          fontWeight: 900,
          fontSize: 82,
          textTransform: 'lowercase',
          color: '#FFFFFF',
          WebkitTextStroke: '12px #000',
          paintOrder: 'stroke fill',
          transform: `scale(${s})`,
          whiteSpace: 'nowrap',
          lineHeight: 1.1,
        }}
      >
        {cur.h}
      </div>
    </AbsoluteFill>
  );
};

