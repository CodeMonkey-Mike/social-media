/** the portrait crop's segment at source time t (FACE windows only; a cover time takes the nearest segment edge) */
const segAt = (t: number) => {
  let best = FACE_SEGS[0];
  let bestD = Infinity;
  for (const s of FACE_SEGS) {
    if (t >= s.from && t < s.to) return s;
    const d = t < s.from ? s.from - t : t - s.to;
    if (d < bestD) {
      bestD = d;
      best = s;
    }
  }
  return best;
};
/** MEASURED crop centre (source px) at source time t: still segments hold, moving segments interpolate their smoothed keys */
const camX = (t: number) => {
  const s = segAt(t);
  const k = s.keys;
  if (k.length === 1 || t <= k[0][0]) return k[0][1];
  if (t >= k[k.length - 1][0]) return k[k.length - 1][1];
  let i = 0;
  while (i < k.length - 2 && k[i + 1][0] <= t) i++;
  const u = (t - k[i][0]) / (k[i + 1][0] - k[i][0]);
  return k[i][1] + (k[i + 1][1] - k[i][1]) * u;
};
/** portrait y of the face centre (the punch / lift pivot) for the segment at t */
const faceY = (t: number) => segAt(t).cy * SV;

