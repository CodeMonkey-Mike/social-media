#!/usr/bin/env node
/** Generates the radial displacement map for the OFFSET "Warp" lens distortion
 * (PR.ADBE Lens Distortion). Encodes an OUTWARD radial field with NONLINEAR
 * (∝ r²) magnitude so feDisplacementMap gives a real barrel/pincushion bulge
 * (uniform scale would not be a lens distortion). R = x-displacement, G = y,
 * 128 = neutral. feDisplacementMap scale = Curvature·K (negative Curvature =
 * negative scale = inward sampling = center magnified = barrel bulge).
 *
 * Writes a small PPM (smooth field, upscaled by the filter), converts to PNG via
 * ffmpeg, base64-inlines it into remotion/src/transitions/engines/lensMap.ts
 * (data-URI so the SVG feImage never waits on an external file load in Chromium).
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const W = 960, H = 540;          // map raster (upscaled smoothly by feImage)
const OVERSCAN = 0.08;           // map covers 8% beyond the frame on every side, so
                                 // the in-filter feGaussianBlur that de-bands the
                                 // 8-bit values never pulls in transparent edge
const A = 26;                    // byte gain (max |nx·r| at the overscanned corner
                                 // ≈ 4.88 → 26 keeps the field un-clipped)
// full-frame normalized geometry: unit = half of the FRAME height (not the raster)
const frameW = 16 / 9, frameH = 1; // in units of frame height
const buf = Buffer.alloc(W * H * 3);
let o = 0;
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    // raster spans the frame + overscan margin, centered on the frame center.
    // nx = frame-space offset (in frame-height units) / (frameH/2). NOTE: an
    // earlier version divided by an extra 2, halving both axes -> r^2 field a
    // QUARTER strength -> the lens rendered ~4x too weak (Mike caught it at
    // full size; thumbnail QA missed the magnitude). No extra /2.
    const nx = ((x / (W - 1)) - 0.5) * (frameW * (1 + 2 * OVERSCAN)) / (frameH / 2);
    const ny = ((y / (H - 1)) - 0.5) * (frameH * (1 + 2 * OVERSCAN)) / (frameH / 2);
    const r = Math.hypot(nx, ny);
    // outward radial, magnitude ∝ r²: dx = (nx/r)·r² = nx·r
    const dx = nx * r, dy = ny * r;
    const R = Math.max(0, Math.min(255, Math.round(128 + A * dx)));
    const G = Math.max(0, Math.min(255, Math.round(128 + A * dy)));
    buf[o++] = R; buf[o++] = G; buf[o++] = 128;
  }
}
const ppm = path.join(__dirname, 'lib', 'lens-map.ppm');
const png = path.join(__dirname, 'lib', 'lens-map.png');
fs.writeFileSync(ppm, Buffer.concat([Buffer.from(`P6\n${W} ${H}\n255\n`), buf]));
execSync(`ffmpeg -y -loglevel error -i "${ppm}" "${png}"`);
fs.unlinkSync(ppm);

// ---- second map: LINEAR radial profile (dx ∝ nx) = per-channel SCALE dispersion
// for the Deviation chromatic tear (channels scaled differently from center =
// prism zoom; the pack's fringes point away from center with a quiet middle).
// Anisotropy GeomX/GeomY = 100/83 baked into dy.
const A2 = 45, GEOM_Y = 0.83, BIAS_NX = 0.55;
// BIAS_NX adds a CONSTANT lateral component to the dispersion (the preview's
// fringes are ~10px even at the frame center, growing radially to ~20-25px —
// not a pure zero-centered radial field). A2 lowered so bias+edge fits 8-bit.
{
  const buf2 = Buffer.alloc(W * H * 3);
  let o2 = 0;
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const nx = ((x / (W - 1)) - 0.5) * (frameW * (1 + 2 * OVERSCAN)) / (frameH / 2);
      const ny = ((y / (H - 1)) - 0.5) * (frameH * (1 + 2 * OVERSCAN)) / (frameH / 2);
      buf2[o2++] = Math.max(0, Math.min(255, Math.round(128 + A2 * (nx + BIAS_NX))));
      buf2[o2++] = Math.max(0, Math.min(255, Math.round(128 + A2 * GEOM_Y * ny)));
      buf2[o2++] = 128;
    }
  }
  const ppm2 = path.join(__dirname, 'lib', 'linear-map.ppm');
  const png2 = path.join(__dirname, 'lib', 'linear-map.png');
  fs.writeFileSync(ppm2, Buffer.concat([Buffer.from(`P6\n${W} ${H}\n255\n`), buf2]));
  execSync(`ffmpeg -y -loglevel error -i "${ppm2}" "${png2}"`);
  fs.unlinkSync(ppm2);
}

const b64 = fs.readFileSync(png).toString('base64');
const b64lin = fs.readFileSync(path.join(__dirname, 'lib', 'linear-map.png')).toString('base64');
const tsPath = path.join(__dirname, '..', '..', 'remotion', 'src', 'transitions', 'engines', 'lensMap.ts');
fs.writeFileSync(tsPath,
  `// AUTO-GENERATED by assets/transitions/_gen-lens-map.js — radial displacement map\n` +
  `// for the OFFSET Warp lens distortion (feDisplacementMap). Do not edit by hand.\n` +
  `export const LENS_MAP = 'data:image/png;base64,${b64}';\n` +
  `/** Map overscan beyond the frame per side (fraction of frame size). */\n` +
  `export const LENS_OVERSCAN = ${OVERSCAN};\n` +
  `/** feDisplacementMap scale per unit |Curvature|, from the Premiere lens model\n` +
  ` * src_r = r·(1+(k/100)·r²) with unit = half frame height (1080p: 540) and the\n` +
  ` * map's byte gain A=${A}: scale = 540·255/(100·A). */\n` +
  `export const LENS_SCALE_PER_K = ${(540 * 255) / (100 * A)};\n` +
  `/** LINEAR radial map (dx ∝ nx, dy ∝ ${GEOM_Y}·ny): per-channel scale dispersion\n` +
  ` * for Deviation. Displacement at the side edge (nx=1.78) = scale·(A2=${A2})/255·1.78. */\n` +
  `export const LINEAR_MAP = 'data:image/png;base64,${b64lin}';\n` +
  `export const LINEAR_A = ${A2};\n`);
console.log(`lens map: ${W}x${H} (overscan ${OVERSCAN}) A=${A} -> ${path.relative(process.cwd(), tsPath)} (${(b64.length / 1024).toFixed(0)}KB)`);
