#!/usr/bin/env node
/** Generates the EDGE-ANCHORED spherize displacement map for the ZOOM Optics
 * lens (PR.ADBE Lens Distortion at BIG curvatures, decoded from the pure-lens
 * "Zoom Optics - In Out 3" preview 2026-07-14):
 *
 *   Negative Curvature = a center-MAGNIFYING bulge whose frame stays FULL —
 *   the distortion is zero at the frame boundary (corner-normalized), maximal
 *   mid-radius. The OFFSET-Warp LENS_MAP (magnitude growing to the EDGE,
 *   calibrated at |k| <= 30) is the WRONG profile out at |k| 70-100: it pulls
 *   the whole frame inward into a black-bordered porthole (probe QA caught it).
 *
 * Model: with n = frame offset in half-frame-height units and rn = r/R_corner
 * (corners at rn = 1): sample u = r + (c/100)·d, d_vec = n_vec·(1 − rn²).
 * c<0 ⇒ samples pull toward center everywhere INSIDE the frame ⇒ magnified
 * center, pinned corners, no fill ever exposed. c>0 (pincushion, only the
 * In Impact overshoot +71) samples outward — its zoom pulse covers the edge.
 * R = x-displacement, G = y, 128 neutral; same raster/overscan conventions as
 * _gen-lens-map.js. Writes remotion/src/transitions/engines/sphereMap.ts.
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const W = 960, H = 540;
const OVERSCAN = 0.08;
const frameW = 16 / 9, frameH = 1;
const R_CORNER = Math.hypot(frameW, frameH) / (frameH); // n-units: hypot(1.778, 1) ≈ 2.04

// find the byte gain: max |component| of d over the overscanned raster
let maxd = 0;
const dAt = (x, y) => {
  const nx = ((x / (W - 1)) - 0.5) * (frameW * (1 + 2 * OVERSCAN)) / (frameH / 2);
  const ny = ((y / (H - 1)) - 0.5) * (frameH * (1 + 2 * OVERSCAN)) / (frameH / 2);
  const rn = Math.hypot(nx, ny) / R_CORNER;
  return [nx * (1 - rn * rn), ny * (1 - rn * rn)];
};
for (let y = 0; y < H; y += 3) for (let x = 0; x < W; x += 3) {
  const [dx, dy] = dAt(x, y);
  maxd = Math.max(maxd, Math.abs(dx), Math.abs(dy));
}
const A = Math.floor(127 / maxd);

const buf = Buffer.alloc(W * H * 3);
let o = 0;
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    const [dx, dy] = dAt(x, y);
    buf[o++] = Math.max(0, Math.min(255, Math.round(128 + A * dx)));
    buf[o++] = Math.max(0, Math.min(255, Math.round(128 + A * dy)));
    buf[o++] = 128;
  }
}
const ppm = path.join(__dirname, 'lib', 'sphere-map.ppm');
const png = path.join(__dirname, 'lib', 'sphere-map.png');
fs.writeFileSync(ppm, Buffer.concat([Buffer.from(`P6\n${W} ${H}\n255\n`), buf]));
execSync(`ffmpeg -y -loglevel error -i "${ppm}" "${png}"`);
fs.unlinkSync(ppm);

const b64 = fs.readFileSync(png).toString('base64');
const tsPath = path.join(__dirname, '..', '..', 'remotion', 'src', 'transitions', 'engines', 'sphereMap.ts');
fs.writeFileSync(tsPath,
  `// AUTO-GENERATED by assets/transitions/_gen-sphere-map.js — edge-anchored\n` +
  `// spherize displacement map for the ZOOM Optics lens. Do not edit by hand.\n` +
  `export const SPHERE_MAP = 'data:image/png;base64,${b64}';\n` +
  `export const SPHERE_OVERSCAN = ${OVERSCAN};\n` +
  `/** feDisplacementMap scale per unit |Curvature|: u = r + (c/100)·n(1−rn²),\n` +
  ` * n in half-frame-height units (1080p: 540 px), byte gain A=${A}. */\n` +
  `export const SPHERE_SCALE_PER_C = ${(540 * 255) / (100 * A)};\n`);
console.log(`sphere map: ${W}x${H} A=${A} maxd=${maxd.toFixed(3)} scalePerC=${((540 * 255) / (100 * A)).toFixed(2)}`);
