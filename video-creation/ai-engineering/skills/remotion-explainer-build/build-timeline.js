// TEMPLATE — copy to the project's scripts/ dir. Set MODULE + PREFIX for this video (2 edits).
// ffprobes each chunk mp3, lays out per-chunk starts with a 0.35s gap (matching stitch-narration.js),
// and emits remotion/src/<MODULE>.ts with <PREFIX>_CHUNKS/_VO_END/_TAIL/_DURATION_FRAMES/_FPS.
// Usage: node scripts/build-timeline.js
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// ── per-video (edit these two) ──────────────────────────────────────────────
const MODULE = 'CHANGEMETimeline'; // -> remotion/src/CHANGEMETimeline.ts
const PREFIX = 'XX';               // export prefix, e.g. ST
// ────────────────────────────────────────────────────────────────────────────
const GAP = 0.35;
const TAIL = 1.6;
const FPS = 30;

const HERE = path.resolve(__dirname, '..');
const AUDIO = path.join(HERE, 'audio');
const CHUNKS = JSON.parse(fs.readFileSync(path.join(HERE, 'tts-chunks.json'), 'utf8'));
const OUT_TS = path.resolve(__dirname, `../../../../remotion/src/${MODULE}.ts`);

const probe = (f) => {
  try {
    const d = parseFloat(execSync(`ffprobe -v error -show_entries format=duration -of csv=p=0 "${f}"`, { encoding: 'utf8' }).trim());
    return Number.isFinite(d) && d > 0 ? d : null;
  } catch { return null; }
};

let missing = 0;
const durs = CHUNKS.map((c) => {
  const f = path.join(AUDIO, c.file);
  const d = fs.existsSync(f) ? probe(f) : null;
  if (d) return d;
  missing++;
  return Math.max(8, c.text.split(/\s+/).length / 2.8);
});

let t = 0;
const rows = CHUNKS.map((c) => {
  const start = t; t += durs[CHUNKS.indexOf(c)] + GAP;
  const nn = c.file.match(/(\d+)/)[1];
  return { start: +start.toFixed(3), audio: `audio/${c.file}`, visual: `render-assets/container-${nn}.png` };
});
const voEnd = +(t - GAP).toFixed(3);
const durationFrames = Math.round((voEnd + TAIL) * FPS);

const banner = `// AUTO-GENERATED by scripts/build-timeline.js — do not hand-edit.\n// ${missing ? missing + ' ESTIMATED (mp3 missing).' : 'all durations measured from real mp3s.'}\n`;
fs.writeFileSync(OUT_TS,
  banner +
  `export const ${PREFIX}_FPS = ${FPS};\n` +
  `export const ${PREFIX}_VO_END = ${voEnd};\n` +
  `export const ${PREFIX}_TAIL = ${TAIL};\n` +
  `export const ${PREFIX}_DURATION_FRAMES = ${durationFrames};\n` +
  `export const ${PREFIX}_CHUNKS: { start: number; audio: string; visual: string }[] = [\n` +
  rows.map((r) => `  { start: ${r.start}, audio: '${r.audio}', visual: '${r.visual}' },`).join('\n') +
  `\n];\n`);
console.log(`wrote ${OUT_TS} — ${rows.length} chunks, VO_END ${voEnd}s, ${durationFrames} frames @${FPS}, estimated:${missing}`);
