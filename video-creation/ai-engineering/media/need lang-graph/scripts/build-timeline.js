// build-timeline.js — measure each chunk-NN.mp3 duration (ffprobe), compute per-chunk
// start times with a 0.35s inter-chunk gap (matching the stitch), and emit a TS timeline
// module the Remotion comp imports. Falls back to a text-length estimate for any missing
// mp3 so the comp still compiles before audio lands (regenerate once audio is downloaded).
// Usage: node scripts/build-timeline.js

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const HERE = path.resolve(__dirname, '..');
const AUDIO = path.join(HERE, 'audio');
const CHUNKS = JSON.parse(fs.readFileSync(path.join(HERE, 'tts-chunks.json'), 'utf8'));
const OUT_TS = path.resolve(__dirname, '../../../../remotion/src/needLangGraphTimeline.ts');
const GAP = 0.35;
const TAIL = 1.6;

const probe = (f) => {
  try {
    const out = execSync(`ffprobe -v error -show_entries format=duration -of csv=p=0 "${f}"`, { encoding: 'utf8' }).trim();
    const d = parseFloat(out);
    return Number.isFinite(d) && d > 0 ? d : null;
  } catch { return null; }
};

let missing = 0;
const durs = CHUNKS.map((c) => {
  const f = path.join(AUDIO, c.file);
  const d = fs.existsSync(f) ? probe(f) : null;
  if (d) return d;
  missing++;
  const words = c.text.split(/\s+/).length;
  return Math.max(8, words / 2.8); // estimate
});

let t = 0;
const rows = CHUNKS.map((c, i) => {
  const start = t;
  t += durs[i] + GAP;
  const nn = c.file.match(/(\d+)/)[1];
  return { start: +start.toFixed(3), audio: `audio/${c.file}`, visual: `render-assets/container-${nn}.png` };
});
const voEnd = +(t - GAP).toFixed(3);

const banner = `// AUTO-GENERATED by scripts/build-timeline.js — do not hand-edit.\n// ${missing ? missing + ' chunk(s) ESTIMATED (mp3 missing) — regenerate after audio downloads.' : 'all durations measured from real mp3s.'}\n`;
const body =
  banner +
  `export const NLG_FPS = 30;\n` +
  `export const NLG_VO_END = ${voEnd};\n` +
  `export const NLG_TAIL = ${TAIL};\n` +
  `export const NLG_CHUNKS: { start: number; audio: string; visual: string }[] = [\n` +
  rows.map((r) => `  { start: ${r.start}, audio: '${r.audio}', visual: '${r.visual}' },`).join('\n') +
  `\n];\n`;

fs.writeFileSync(OUT_TS, body);
console.log(`wrote ${OUT_TS}`);
console.log(`chunks: ${rows.length}, VO_END: ${voEnd}s (${(voEnd / 60).toFixed(2)} min), missing/estimated: ${missing}`);
