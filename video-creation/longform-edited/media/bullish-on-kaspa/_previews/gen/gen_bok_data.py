# generates remotion/src/BullishOnKaspaData.ts: the KT caption phrases (cue = the spoken word's onset) + chart geometry from the chart-builder's html
import json,re,sys
P='C:/Users/mnede/Documents/Claude/social-media/video-creation/'
M=P+'longform-edited/media/bullish-on-kaspa/'
d=json.load(open(M+'spine/ALL.d.desilenced.medium-words.json',encoding='utf8'))
W=[]
for s in d['segments']:
    for w in s.get('words',[]): W.append((w['start'],w['end'],re.sub(r"[^a-z0-9']",'',w['word'].lower().replace('’',"'"))))
def tc(s):
    m,x=s.split(':'); return int(m)*60+float(x)
faces=json.load(open(M+'COVER-PLAN.json',encoding='utf8'))['face_windows']
rows=[]
for line in open(M+'EDIT-PLAN.md',encoding='utf8'):
    m=re.match(r'(\d+:\d\d\.\d)\s+\[KT-CAPTION\]\s+(.*)',line)
    if not m: continue
    t=tc(m.group(1)); body=m.group(2)
    q=re.search(r'"([^"]+)"',body); txt=q.group(1)
    acc=re.search(r'\(([^()]*?) in the accent',body)
    keys=[]
    if acc:
        a=acc.group(1)
        keys=[x.strip() for x in re.split(r'\band\b|,',a) if x.strip()]
        # 'BEAR' etc only the leading token(s) before a comma note
    kind='pop' if 'two_colour_pop' in body else ('open' if 'open_stretch' in body else 'cut')
    first=re.sub(r"[^a-z0-9']",'',txt.split()[0].lower().replace('’',"'"))
    # snap to the spoken first word within +-0.45 s of the row's tc
    best=None
    for a,b,w in W:
        if abs(a-t)<=0.45 and (w==first or w.startswith(first) or first.startswith(w) and w):
            if best is None or abs(a-t)<abs(best-t): best=a
    rows.append(dict(t=round(best if best is not None else t,3),snapped=best is not None,h=txt,keys=keys,kind=kind))
for r in rows: print(r['t'],'S' if r['snapped'] else '-',r['kind'],r['h'],r['keys'])
out=['// BullishOnKaspaData.ts: GENERATED by _previews/gen/gen_bok_data.py from EDIT-PLAN.md [KT-CAPTION] rows (cue = the spoken word onset) and the chart-builder html (geometry).','']
out.append('export const KT_PHRASES: { t: number; h: string; keys: string[]; kind: string }[] = [')
for r in rows:
    out.append("  { t: %.3f, h: %s, keys: %s, kind: '%s' },"%(r['t'],json.dumps(r['h'],ensure_ascii=False),json.dumps(r['keys'],ensure_ascii=False),r['kind']))
out.append('];'); out.append('')
def frames(fn):
    s=open(M+'assets/charts/'+fn,encoding='utf8').read()
    idx=[m.start() for m in re.finditer(r'<div class="frame',s)]
    o={}
    for a,b in zip(idx,idx[1:]+[len(s)]):
        f=s[a:b]; o[re.search(r'id="([^"]+)"',f).group(1)]=f
    return o
fr=frames('C4.html')['payoff']
out.append('export const C4_PATH = %s;'%json.dumps(re.search(r'd="(M270\.0,[^"]+)"',fr).group(1)))
f2=frames('C2.html')['A-payoff']
paths=re.findall(r'<path d="(M850,[^"]+)"',f2)
out.append('export const C2_REWARD = %s;'%json.dumps(paths[0])); out.append('export const C2_SUPPLY = %s;'%json.dumps(paths[1]))
f7=frames('C17.html')['payoff']
dots=re.findall(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="10.5" fill="(#[0-9A-F]+)"',f7)
out.append('export const C17_DOTS: [number, number, number][] = ['+','.join('[%s,%s,%d]'%(x,y,{'#8A877E':0,'#CFCBC0':1,'#49EACB':2}[c]) for x,y,c in dots)+'];')
open(P+'remotion/src/BullishOnKaspaData.ts','w',encoding='utf8').write('\n'.join(out)+'\n')
print(len(dots),len(paths))
# start/mid frames text deltas
for fn in ['C2.html','C3.html','C4.html','C17.html']:
    for k,f in frames(fn).items():
        print(fn,k,re.findall(r'<div class="head">.*?</div></div>|<h1>.*?</h1>',f)[0][:140], '| src', (re.findall(r'class="src">(.*?)</div>',f) or [''])[0][:40])
