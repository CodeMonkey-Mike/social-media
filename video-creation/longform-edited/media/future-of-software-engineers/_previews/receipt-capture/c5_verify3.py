from rc_lib import *
import re
base = "https://blog.google/company-news/inside-google/message-ceo/"
slugs = ["alphabet-earnings-q3-2026/", "next-chapter-ai-momentum/", "alphabet-earnings-q2-2026/", "alphabet-earnings-q1-2026/"]
with sync_playwright() as p:
    for s in slugs:
        print("=====", base+s)
        b, pg = open_page(p, base+s, wait=4, dsf=1)
        body = pg.inner_text("body")
        m = re.search(r"(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]* \d{1,2}, 202\d", body)
        print("title:", pg.title(), "| date:", m.group(0) if m else "?", "| chars", len(body))
        hits = [mm for mm in re.finditer(r"(?i)(new code|code at Google|of (?:all )?(?:the )?code|code (?:is|are|was|were) (?:now )?(?:AI|generated|written)|AI-generated|generated by AI|written by AI|AI-written|coding)", body)]
        print("hits:", len(hits))
        for mm in hits[:8]:
            st = max(0, mm.start()-160); print("  >>", body[st:mm.end()+200].replace("\n"," | "))
        b.close()
