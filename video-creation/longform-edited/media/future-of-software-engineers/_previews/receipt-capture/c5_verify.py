from rc_lib import *
import re
urls = ["https://blog.google/inside-google/message-ceo/alphabet-earnings-q3-2026/",
        "https://blog.google/inside-google/message-ceo/alphabet-earnings-q2-2026/",
        "https://blog.google/inside-google/message-ceo/alphabet-earnings-q1-2026/"]
with sync_playwright() as p:
    for u in urls:
        print("=====", u)
        b, pg = open_page(p, u, wait=4, h=1080, dsf=1)
        try:
            title = pg.title(); body = pg.inner_text("body")
            print("title:", title, "| chars", len(body))
            for m in re.finditer(r"(?i)(new code|of (all )?code|code at Google|AI-generated|generated by AI)", body):
                s = max(0, m.start()-150); print("  HIT:", body[s:m.end()+200].replace("\n"," | ")); 
        except Exception as e:
            print("ERR", e)
        b.close()
